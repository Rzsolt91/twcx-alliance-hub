const DICTIONARIES = { en, ko };

let active = "en";

export function setLanguage(code) {
  active = DICTIONARIES[code] ? code : "en";
  document.documentElement.lang = active;
}

export function currentLanguage() {
  return active;
}

/** Translates a key, substituting `{name}` placeholders. */
export function t(key, vars) {
  const template = DICTIONARIES[active]?.[key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

/** Locale tag for `Intl` formatting in the active language. */
export function locale() {
  return active === "ko" ? "ko-KR" : "en-GB";
}
